function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

/** Immersive routes render their own full-bleed chrome (menu screen, console). */
const BARE_ROUTES = new Set(["/", "/build"]);

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  // The admin console (AdminShell) is a separate chrome from the rest of the
  // site — it must never sit inside SiteHeader/SiteFooter, which carry
  // consumer-facing nav ("Start Building", Home, Compare) that has no place
  // in a tool for managing the catalog and user roles. Prefix match covers
  // every /admin/* child route, not just the bare /admin path.
  const bare = BARE_ROUTES.has(pathname) || pathname.startsWith("/admin");

  return (
    <QueryClientProvider client={queryClient}>
      {bare ? (
        <Outlet />
      ) : (
        <div className="flex min-h-screen flex-col bg-background">
          <SiteHeader />
          <main className="flex-1">
            {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
            <Outlet />
          </main>
          <SiteFooter />
        </div>
      )}
      <Toaster position="bottom-right" />
    </QueryClientProvider>
  );
}